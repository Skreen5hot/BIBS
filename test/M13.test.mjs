// ── §17.3 item 2: validity invariant — every schema node has type XOR oneOf ──
{
  function hasValidShape(s) {
    if (s === null || typeof s !== 'object') return false;
    const hasType  = 'type'  in s;
    const hasOneOf = 'oneOf' in s;
    return (hasType || hasOneOf) && !(hasType && hasOneOf);
  }

  // primitive non-nullable
  {
    const p = { kind: 'primitive', id: '#/x', primitiveType: 'boolean', nullable: false,
                occurrences: 1, typeDistribution: { boolean: 1 } };
    const o = { kind: 'object', id: '#', occurrences: 1,
                properties: [{ name: 'x', required: true, occurrences: 1, totalPopulation: 1, target: p }] };
    assert(hasValidShape(toJsonSchema(makeCism(o, 'json-object')).properties.x),
           '§17.3 item2: primitive non-nullable — type XOR oneOf');
  }

  // nullable primitive
  {
    const p = { kind: 'primitive', id: '#/x', primitiveType: 'number', nullable: true,
                occurrences: 3, typeDistribution: { number: 2, null: 1 } };
    const o = { kind: 'object', id: '#', occurrences: 3,
                properties: [{ name: 'x', required: true, occurrences: 3, totalPopulation: 3, target: p }] };
    const px = toJsonSchema(makeCism(o, 'json-object')).properties.x;
    assert(hasValidShape(px),             '§17.3 item2: nullable primitive — type XOR oneOf');
    assert(Array.isArray(px.type),        '§17.3 item2: nullable primitive type is array');
  }

  // null primitive
  {
    const p = { kind: 'primitive', id: '#/x', primitiveType: 'null', nullable: true,
                occurrences: 2, typeDistribution: { null: 2 } };
    const o = { kind: 'object', id: '#', occurrences: 2,
                properties: [{ name: 'x', required: true, occurrences: 2, totalPopulation: 2, target: p }] };
    assert(hasValidShape(toJsonSchema(makeCism(o, 'json-object')).properties.x),
           '§17.3 item2: null primitive — type XOR oneOf');
  }

  // object root (json-object)
  {
    const o = { kind: 'object', id: '#', occurrences: 0, properties: [] };
    assert(hasValidShape(toJsonSchema(makeCism(o, 'json-object'))),
           '§17.3 item2: object root — type XOR oneOf');
  }

  // array items node (csv-wrapped): csv wraps array root once, so .items = mapNode(arrayRoot)
  {
    const i = { kind: 'primitive', id: '#/[]', primitiveType: 'integer', nullable: false,
                occurrences: 1, typeDistribution: { integer: 1 } };
    const a = { kind: 'array', id: '#', itemType: i, occurrences: 1, nullable: false };
    const s = toJsonSchema(makeCism(a, 'csv'));
    assert(hasValidShape(s.items),       '§17.3 item2: mapped array node — type XOR oneOf');
    assert(hasValidShape(s.items.items), '§17.3 item2: array items child — type XOR oneOf');
  }

  // union non-nullable — csv+array-root: union sits at .items.items
  {
    const m1 = { kind: 'primitive', id: '#/[]/|0', primitiveType: 'string', nullable: false,
                 occurrences: 1, typeDistribution: { string: 1 } };
    const m2 = { kind: 'object', id: '#/[]/|1', properties: [], occurrences: 1 };
    const u  = { kind: 'union', id: '#/[]', nullable: false, occurrences: 2, members: [m1, m2] };
    const a  = { kind: 'array', id: '#', itemType: u, occurrences: 2, nullable: false };
    const items = toJsonSchema(makeCism(a, 'csv')).items.items;
    assert(hasValidShape(items),         '§17.3 item2: union non-nullable — type XOR oneOf');
    assert(!('type' in items),           '§17.3 item2: union has no type key');
    assert('oneOf' in items,             '§17.3 item2: union has oneOf key');
    assert(items.oneOf.every(m => hasValidShape(m)), '§17.3 item2: each union member — type XOR oneOf');
  }

  // union nullable — appended null member also valid; csv+array-root: union at .items.items
  {
    const m1 = { kind: 'primitive', id: '#/[]/|0', primitiveType: 'string', nullable: false,
                 occurrences: 1, typeDistribution: { string: 1 } };
    const u  = { kind: 'union', id: '#/[]', nullable: true, occurrences: 2, members: [m1] };
    const a  = { kind: 'array', id: '#', itemType: u, occurrences: 2, nullable: false };
    const items = toJsonSchema(makeCism(a, 'csv')).items.items;
    assert(hasValidShape(items), '§17.3 item2: nullable union — type XOR oneOf');
    const nullMember = items.oneOf[items.oneOf.length - 1];
    assert(hasValidShape(nullMember), '§17.3 item2: appended null member — type XOR oneOf');
    assert(nullMember.type === 'null', '§17.3 item2: appended null member type=null');
  }
}
