// JSON Schema Draft 2020-12 adapter — §11.1

export function toJsonSchema(cism) {
  const inputHash   = cism?.inputHash   ?? '0'.repeat(64);
  const inputSource = cism?.inputSource ?? 'csv';

  const meta = {
    $schema:  'https://json-schema.org/draft/2020-12/schema',
    $id:      `urn:bibss:inferred:${inputHash}`,
    title:    'Inferred Schema',
    $comment: 'Generated by BIBSS v1.3',
  };

  const rootNode    = cism?.root ?? null;
  const isArrayRoot = inputSource === 'csv' || inputSource === 'json-array';

  if (isArrayRoot) {
    return {
      ...meta,
      type:  'array',
      items: rootNode !== null ? mapNode(rootNode) : {},
    };
  }

  const nodeSchema = rootNode !== null
    ? mapNode(rootNode)
    : { type: 'object', properties: {}, required: [] };
  return { ...meta, ...nodeSchema };
}

function mapNode(node) {
  if (!node) return {};
  switch (node.kind) {
    case 'primitive': return mapPrimitive(node);
    case 'object':    return mapObject(node);
    case 'array':     return mapArray(node);
    case 'union':     return mapUnion(node);
    default:          return {};
  }
}

function mapPrimitive(node) {
  if (node.primitiveType === 'null') return { type: 'null' };
  if (node.nullable) return { type: [node.primitiveType, 'null'] };
  return { type: node.primitiveType };
}

function mapObject(node) {
  const properties = {};
  const required   = [];
  for (const edge of node.properties ?? []) {
    properties[edge.name] = mapNode(edge.target);
    if (edge.required) required.push(edge.name);
  }
  return { type: 'object', properties, required };
}

function mapArray(node) {
  const schema = { type: 'array' };
  if (node.itemType != null) schema.items = mapNode(node.itemType);
  return schema;
}

function mapUnion(node) {
  const memberSchemas = (node.members ?? []).map(m => mapNode(m));
  if (node.nullable) return { oneOf: [...memberSchemas, { type: 'null' }] };
  return { oneOf: memberSchemas };
}
